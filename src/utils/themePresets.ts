/**
 * Applies the CSS variables of the specified theme to the document root element.
 */
export function applyTheme(themeId: string): ThemePreset {
  const preset = THEME_PRESETS.find((p) => p.id === themeId) || THEME_PRESETS[0];
  const root = document.documentElement;

  root.style.setProperty("--bg-canvas", preset.colors.bgCanvas);
  root.style.setProperty("--bg-surface-base", preset.colors.bgSurfaceBase);
  root.style.setProperty("--bg-surface-card", preset.colors.bgSurfaceCard);
  root.style.setProperty("--bg-surface-elevated", preset.colors.bgSurfaceElevated);
  root.style.setProperty("--bg-surface-input", preset.colors.bgSurfaceInput);

  root.style.setProperty("--border-subtle", preset.colors.borderSubtle);
  root.style.setProperty("--border-medium", preset.colors.borderMedium);
  root.style.setProperty("--border-glow", preset.colors.borderGlow);

  root.style.setProperty("--accent-brand", preset.colors.accentBrand);
  root.style.setProperty("--accent-brand-bright", preset.colors.accentBrandBright);
  root.style.setProperty("--accent-safety", preset.colors.accentSafety);
  root.style.setProperty("--accent-warning", preset.colors.accentWarning);
  root.style.setProperty("--accent-danger", preset.colors.accentDanger);

  root.style.setProperty("--text-primary", preset.colors.textPrimary);
  root.style.setProperty("--text-secondary", preset.colors.textSecondary);
  root.style.setProperty("--text-muted", preset.colors.textMuted);

  root.setAttribute("data-theme", preset.id);
  localStorage.setItem("cuddle_theme", preset.id);

  return preset;
}

/**
 * Retrieves the currently saved theme ID from localStorage or returns default.
 */
export function getSavedThemeId(): string {
  return localStorage.getItem("cuddle_theme") || "cyber-midnight-teal";
}
